const safeLink = (url) => {
  try {
    const parsed = new URL(url);
    return ["https:", "http:"].includes(parsed.protocol) &&
      !parsed.username &&
      !parsed.password
      ? parsed.href
      : null;
  } catch {
    return null;
  }
};

export function CitedText({ text, citations = [], prefix }) {
  const byId = new Map(
    citations.map((source, index) => [source.id, { ...source, index }]),
  );
  return String(text || "")
    .split(/(\*\*[^*]+\*\*|\[\[cite:[^\]\r\n]+\]\])/g)
    .map((part, index) => {
      if (part.startsWith("**") && part.endsWith("**")) return <strong key={index}><CitedText text={part.slice(2, -2)} citations={citations} prefix={prefix} /></strong>;
      const id = /^\[\[cite:([^\]\r\n]+)\]\]$/.exec(part)?.[1];
      const source = byId.get(id);
      return source ? (
        <a
          className="zai-citation"
          key={index}
          href={`#${prefix}-source-${source.index}`}
          title={source.title}
          aria-label={`Source ${source.index + 1}: ${source.title}`}
        >
          [{source.index + 1}]
        </a>
      ) : (
        <React.Fragment key={index}>{part}</React.Fragment>
      );
    });
}

// A small, text-only research renderer: no raw HTML or generated links execute.
export function ResearchText({ text, citations = [], prefix }) {
  const blocks = [];
  let paragraph = [], list = [];
  const inline = (value) => <CitedText text={value} citations={citations} prefix={prefix} />;
  const flushParagraph = () => { if (paragraph.length) { blocks.push(<p key={blocks.length}>{inline(paragraph.join("\n"))}</p>); paragraph = []; } };
  const flushList = () => { if (list.length) { blocks.push(<ul key={blocks.length}>{list.map((line, i) => <li key={i}>{inline(line)}</li>)}</ul>); list = []; } };
  for (const line of String(text || "").split("\n")) {
    const heading = /^#{1,6}\s+(.+)$/.exec(line);
    const bullet = /^\s*(?:[-*]|\d+[.)])\s+(.+)$/.exec(line);
    if (heading) { flushParagraph(); flushList(); blocks.push(<h4 key={blocks.length}>{inline(heading[1])}</h4>); }
    else if (bullet) { flushParagraph(); list.push(bullet[1]); }
    else if (!line.trim() || /^[-*_]{3,}$/.test(line.trim())) { flushParagraph(); flushList(); }
    else { flushList(); paragraph.push(line); }
  }
  flushParagraph(); flushList();
  return <div className="research-text">{blocks}</div>;
}

function exportText(result) {
  const sources = result.citations || [];
  return `${result.text}${result.diagram ? `\n\nConcept map\n${result.diagram.nodes.map((node) => `${node.id}: ${node.label}`).join("\n")}\n${result.diagram.edges.map((edge) => `${edge.from} → ${edge.to}${edge.label ? ` (${edge.label})` : ""}`).join("\n")}` : ""}\n\n${sources.length ? `Sources\n${sources.map((source) => `[[cite:${source.id}]] ${source.title}${source.url ? ` — ${source.url}` : ""}`).join("\n")}\n\n` : ""}Generated by ${result.model} on ${new Date(result.generatedAt).toLocaleString()}.\n${(result.warnings || []).join("\n")}`;
}

export default function AiPanel({
  task,
  prompt,
  evidence = [],
  onResult,
  label = "Generate with AI",
  autoGenerate = false,
}) {
  const { saveNote } = useApp();
  const [status, setStatus] = useState(null);
  const [statusError, setStatusError] = useState("");
  const [checking, setChecking] = useState(false);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [result, setResult] = useState(null);
  const [actionMessage, setActionMessage] = useState("");
  const controller = useRef(null);
  const checkController = useRef(null);
  const requestId = useRef(0);
  const autoAttempt = useRef("");
  const prefix = useId();
  const evidenceKey = JSON.stringify(evidence);

  async function checkStatus() {
    checkController.current?.abort();
    const next = new AbortController();
    checkController.current = next;
    setChecking(true);
    setStatusError("");
    try {
      const response = await fetch("/api/ai/status", { signal: next.signal });
      if (!response.ok)
        throw new Error("Unable to check the AI provider. Please try again.");
      const data = await response.json();
      if (!next.signal.aborted) setStatus(data);
    } catch (failure) {
      if (!next.signal.aborted)
        setStatusError(failure.message || "Unable to check the AI provider.");
    } finally {
      if (!next.signal.aborted) setChecking(false);
    }
  }

  useEffect(() => {
    checkStatus();
    return () => {
      controller.current?.abort();
      checkController.current?.abort();
    };
  }, []);
  useEffect(() => {
    requestId.current += 1;
    controller.current?.abort();
    setBusy(false);
    setError("");
    setResult(null);
    setActionMessage("");
  }, [task, prompt, evidenceKey]);

  async function generate() {
    if (busy || !prompt?.trim()) return;
    const id = ++requestId.current;
    const next = new AbortController();
    controller.current?.abort();
    controller.current = next;
    setBusy(true);
    setError("");
    setActionMessage("");
    try {
      const response = await fetch("/api/ai/generate", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        signal: next.signal,
        body: JSON.stringify({
          task,
          prompt,
          evidence: evidence.map((source, index) => ({
            id: String(index + 1),
            title: source.title || "Supplied document",
            url: source.url || "",
            abstract: source.abstract || "",
          })),
        }),
      });
      const data = await response.json();
      if (!response.ok) {
        if (data.code === "AI_NOT_CONFIGURED") checkStatus();
        throw new Error(data.error || "The AI request could not be completed.");
      }
      if (requestId.current === id && !next.signal.aborted) {
        setResult(data);
        onResult?.(data);
      }
    } catch (failure) {
      if (requestId.current === id && !next.signal.aborted)
        setError(failure.message || "The AI request could not be completed.");
    } finally {
      if (requestId.current === id && !next.signal.aborted) setBusy(false);
    }
  }

  async function copyResult() {
    try {
      await navigator.clipboard.writeText(exportText(result));
      setActionMessage("Copied with source references.");
    } catch {
      setActionMessage(
        "Copy is unavailable in this browser. Download the text instead.",
      );
    }
  }

  useEffect(() => {
    const key = task + prompt + evidenceKey;
    if (autoGenerate && status?.configured && autoAttempt.current !== key) {
      autoAttempt.current = key;
      generate();
    }
  }, [autoGenerate, status?.configured, task, prompt, evidenceKey]);

  const configured = status?.configured === true;
  const sources = result?.citations || [];
  const excessive = evidence.length > 24;
  return (
    <section
      className="zai-panel"
      aria-label="ScrapeTx Ai research assistant"
      aria-busy={busy}
    >
      <div className="zai-header">
        <span className="zai-heading">
          <Sparkles size={17} aria-hidden="true" /> ScrapeTx Ai
        </span>
        {configured && <span className="zai-provider">Ready to help</span>}
      </div>
      {!status && !statusError && (
        <p className="zai-note" role="status">
          Checking AI configuration…
        </p>
      )}
      {statusError && (
        <div className="zai-setup">
          <p role="alert">{statusError}</p>
          <button
            className="zai-secondary"
            onClick={checkStatus}
            disabled={checking}
          >
            <RefreshCw size={15} aria-hidden="true" /> Check again
          </button>
        </div>
      )}
      {status && !configured && (
        <div className="zai-setup">
          <p>
            <strong>Connect your AI provider to generate research.</strong>
          </p>
          <p>
            {status.error ||
              "Add your server-side API key and model in the integrations setup, then restart the API server."}
          </p>
          {!!status.missing?.length && (
            <p className="zai-note">Missing: {status.missing.join(", ")}</p>
          )}
          <div className="zai-controls">
            <Link to="/integrations" className="zai-secondary">
              Open integrations <ArrowUpRight size={15} aria-hidden="true" />
            </Link>
            <button
              className="zai-secondary"
              onClick={checkStatus}
              disabled={checking}
            >
              <RefreshCw size={15} aria-hidden="true" />{" "}
              {checking ? "Checking…" : "Check again"}
            </button>
          </div>
        </div>
      )}
      {configured && (
        <p className="zai-note">
          {evidence.length
            ? `${evidence.length} supplied ${evidence.length === 1 ? "source" : "sources"} will be sent to your AI provider.`
            : "No source evidence selected. Responses will be marked as unverified."}
        </p>
      )}
      {excessive && (
        <p className="zai-error" role="alert">
          Select up to 24 papers for one AI request.
        </p>
      )}
      <div className="zai-controls">
        <button
          className="zai-generate"
          onClick={generate}
          disabled={!configured || busy || !prompt?.trim() || excessive}
        >
          {busy ? (
            <LoaderCircle
              className="zai-spinner"
              size={16}
              aria-hidden="true"
            />
          ) : (
            <Sparkles size={16} aria-hidden="true" />
          )}
          {busy ? "Researching…" : label}
        </button>
        {busy && (
          <button
            className="zai-secondary"
            onClick={() => {
              requestId.current += 1;
              controller.current?.abort();
              setBusy(false);
            }}
          >
            Cancel
          </button>
        )}
      </div>
      {busy && (
        <p className="zai-note" role="status">
          Reviewing the request and supplied evidence. This can take up to a
          minute.
        </p>
      )}
      {error && (
        <p className="zai-error" role="alert">
          {error}
        </p>
      )}
      {result && (
        <div className="zai-result">
          <div className="zai-result-header">
            <strong>{result.diagram?.title || "Research response"}</strong>
            <span>ScrapeTx Ai</span>
          </div>
          <div className="zai-output">
            <ResearchText text={result.text} citations={sources} prefix={prefix} />
          </div>
          {result.diagram && (
            <div className="zai-diagram">
              <div className="zai-nodes">
                {result.diagram.nodes.map((node) => (
                  <div className="zai-node" key={node.id}>
                    <small>{node.id}</small>
                    <span>{node.label}</span>
                  </div>
                ))}
              </div>
              {!!result.diagram.edges.length && (
                <ul className="zai-edges">
                  {result.diagram.edges.map((edge, index) => (
                    <li key={index}>
                      {
                        result.diagram.nodes.find(
                          (node) => node.id === edge.from,
                        )?.label
                      }{" "}
                      →{" "}
                      {
                        result.diagram.nodes.find((node) => node.id === edge.to)
                          ?.label
                      }
                      {edge.label ? ` · ${edge.label}` : ""}
                    </li>
                  ))}
                </ul>
              )}
            </div>
          )}
          {!!sources.length && (
            <div className="zai-sources">
              <strong>Sources cited</strong>
              <ol>
                {sources.map((source, index) => (
                  <li id={`${prefix}-source-${index}`} key={source.id}>
                    {safeLink(source.url) ? (
                      <a
                        href={safeLink(source.url)}
                        target="_blank"
                        rel="noopener noreferrer"
                      >
                        {source.title}{" "}
                        <ArrowUpRight size={13} aria-hidden="true" />
                      </a>
                    ) : (
                      <span>{source.title}</span>
                    )}
                    <small>{source.id}</small>
                  </li>
                ))}
              </ol>
            </div>
          )}
          <p className="zai-note">{result.warnings?.join(" ")}</p>
          <div className="zai-controls">
            <button className="zai-secondary" onClick={async () => {
              try {
                await saveNote({title: result.diagram?.title || prompt.slice(0,100), content: exportText(result), citations: result.citations || [], assistant: "ScrapeTx Ai"});
                setActionMessage("Saved to My Library.");
              } catch (e) { setActionMessage(e.message); }
            }}><Bookmark size={15} aria-hidden="true"/> Save to library</button>
            <button className="zai-secondary" onClick={copyResult}>
              {actionMessage.startsWith("Copied") ? (
                <Check size={15} aria-hidden="true" />
              ) : (
                <Copy size={15} aria-hidden="true" />
              )}{" "}
              Copy response
            </button>
            <button
              className="zai-secondary"
              onClick={() =>
                download(
                  `zntx-${task}-${new Date().toISOString().slice(0, 10)}.txt`,
                  exportText(result),
                )
              }
            >
              <Download size={15} aria-hidden="true" /> Download text
            </button>
          </div>
          {actionMessage && (
            <p className="zai-note" role="status">
              {actionMessage}
            </p>
          )}
        </div>
      )}
    </section>
  );
}
